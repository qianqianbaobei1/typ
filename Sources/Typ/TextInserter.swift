import AppKit
import ApplicationServices

/// Puts text into the focused app by pasting, and reads the current selection.
/// Built with industrial-grade clipboard preservation to prevent data loss.
enum TextInserter {
    /// Tags synthetic key events so our own hotkey monitor ignores them.
    static let marker: Int64 = 0x5459_5021

    static func postKey(_ code: CGKeyCode, flags: CGEventFlags) {
        let src = CGEventSource(stateID: .privateState)
        for down in [true, false] {
            guard let e = CGEvent(keyboardEventSource: src, virtualKey: code, keyDown: down) else { continue }
            e.flags = flags
            e.setIntegerValueField(.eventSourceUserData, value: marker)
            e.post(tap: .cghidEventTap)
        }
    }

    /// Transient markers recognized by macOS and popular clipboard managers (Raycast, Paste, Maccy, CleanClip).
    private static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    private static let raycastTransientType = NSPasteboard.PasteboardType("com.raycast.macos.pasteboard.transient")

    /// Full-fidelity clipboard backup and restoration snapshot.
    struct ClipboardBackup {
        struct ItemData {
            let type: NSPasteboard.PasteboardType
            let data: Data
        }
        let items: [[ItemData]]
        let changeCount: Int

        static func capture(from pb: NSPasteboard = .general) -> ClipboardBackup {
            let count = pb.changeCount
            let items: [[ItemData]] = (pb.pasteboardItems ?? []).map { item in
                item.types.compactMap { t in
                    item.data(forType: t).map { ItemData(type: t, data: $0) }
                }
            }
            return ClipboardBackup(items: items, changeCount: count)
        }

        func restore(to pb: NSPasteboard = .general) {
            // If the clipboard was empty when captured, clear it back.
            guard !items.isEmpty else {
                pb.clearContents()
                return
            }
            pb.clearContents()
            let restoredItems: [NSPasteboardItem] = items.map { pairs in
                let item = NSPasteboardItem()
                for p in pairs {
                    item.setData(p.data, forType: p.type)
                }
                return item
            }
            pb.writeObjects(restoredItems)
        }
    }

    @MainActor
    static func paste(_ text: String, preserveClipboard: Bool = true) async {
        await paste(plain: text, html: nil, preserveClipboard: preserveClipboard)
    }

    /// Smart text insertion with automatic fallback:
    /// For normal apps: uses zero-loss clipboard snapshot with HTML/PlainText dual injection and ⌘V.
    /// For terminals and secure fields: automatically falls back to direct Unicode typing (aligns with Typeless findKeyCodeForCharacter).
    @MainActor
    static func insert(plain text: String, html: String?, context: AppContext?, preserveClipboard: Bool = true) async {
        if let ctx = context, (ctx.isTerminalApp || ctx.isSecureField) {
            typeUnicode(text)
            return
        }
        await paste(plain: text, html: html, preserveClipboard: preserveClipboard)
    }

    /// Pastes plain text, optionally with an HTML/RTF rendering for apps that accept formatting.
    /// Captures the full clipboard snapshot beforehand, waits for target app consumption, and restores cleanly.
    @MainActor
    static func paste(plain text: String, html: String?, preserveClipboard: Bool = true) async {
        let pb = NSPasteboard.general
        let backup = ClipboardBackup.capture(from: pb)

        pb.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        if let html {
            item.setString(html, forType: .html)
            if let rtf = RichText.rtf(fromHTML: html) { item.setData(rtf, forType: .rtf) }
        }

        // Tag transient markers so clipboard history tools do not record our temporary injection
        item.setData(Data(), forType: transientType)
        item.setData(Data(), forType: autoGeneratedType)
        item.setData(Data(), forType: raycastTransientType)

        pb.writeObjects([item])
        let injectedChangeCount = pb.changeCount

        // Dispatch ⌘V paste shortcut
        postKey(9, flags: .maskCommand)

        guard preserveClipboard else { return }

        // Wait a brief window (180ms) for the target app's event loop to consume the paste event
        try? await Task.sleep(nanoseconds: 180_000_000)

        // Only restore if the clipboard hasn't been deliberately overwritten by a new user copy
        // or if it still contains our transient marker.
        let currentTypes = pb.types ?? []
        let stillHasOurItem = currentTypes.contains(transientType) || currentTypes.contains(raycastTransientType)
        if pb.changeCount == injectedChangeCount || stillHasOurItem {
            backup.restore(to: pb)
        }
    }

    /// Posts raw Unicode string directly into focused application without touching the clipboard.
    /// Aligns with official Typeless libInputHelper fallback for terminal / secure input / paste-restricted apps.
    static func typeUnicode(_ text: String) {
        let src = CGEventSource(stateID: .privateState)
        for ch in text.utf16 {
            var char = ch
            if let down = CGEvent(keyboardEventSource: src, virtualKey: 0, keyDown: true) {
                down.keyboardSetUnicodeString(stringLength: 1, unicodeString: &char)
                down.setIntegerValueField(.eventSourceUserData, value: marker)
                down.post(tap: .cghidEventTap)
            }
            if let up = CGEvent(keyboardEventSource: src, virtualKey: 0, keyDown: false) {
                up.keyboardSetUnicodeString(stringLength: 1, unicodeString: &char)
                up.setIntegerValueField(.eventSourceUserData, value: marker)
                up.post(tap: .cghidEventTap)
            }
        }
    }

    /// Reads the whole content of the focused input box with ⌘A ⌘C, restores the clipboard,
    /// and puts the caret back at the end. Used where Accessibility can't read the field (e.g. WeChat).
    @MainActor
    static func copyAllInFocusedField() async -> String? {
        let pb = NSPasteboard.general
        let backup = ClipboardBackup.capture(from: pb)
        let before = pb.changeCount
        postKey(0, flags: .maskCommand) // ⌘A
        try? await Task.sleep(nanoseconds: 40_000_000)
        postKey(8, flags: .maskCommand) // ⌘C
        for _ in 0..<15 where pb.changeCount == before {
            try? await Task.sleep(nanoseconds: 20_000_000)
        }
        var text: String?
        if pb.changeCount != before {
            text = pb.string(forType: .string)
            backup.restore(to: pb)
        }
        postKey(124, flags: []) // → collapses the selection to the end
        try? await Task.sleep(nanoseconds: 30_000_000)
        return text
    }

    @MainActor
    static func copyToClipboard(_ text: String) {
        NSPasteboard.general.clearContents()
        NSPasteboard.general.setString(text, forType: .string)
    }

    /// Selected text in the focused app: Accessibility first, then a simulated ⌘C as fallback.
    @MainActor
    static func selectedText() async -> String? {
        if let s = axSelectedText(), !s.isEmpty { return s }
        let pb = NSPasteboard.general
        let backup = ClipboardBackup.capture(from: pb)
        let before = pb.changeCount
        postKey(8, flags: .maskCommand) // ⌘C
        try? await Task.sleep(nanoseconds: 180_000_000)
        guard pb.changeCount != before else { return nil }
        let s = pb.string(forType: .string)
        backup.restore(to: pb)
        return (s?.isEmpty ?? true) ? nil : s
    }

    private static func axSelectedText() -> String? {
        let sys = AXUIElementCreateSystemWide()
        var focused: CFTypeRef?
        guard AXUIElementCopyAttributeValue(sys, kAXFocusedUIElementAttribute as CFString, &focused) == .success,
              let focused else { return nil }
        var value: CFTypeRef?
        guard AXUIElementCopyAttributeValue(focused as! AXUIElement, kAXSelectedTextAttribute as CFString, &value) == .success
        else { return nil }
        return value as? String
    }

    /// Deletes backwards (Backspace) by `count` times.
    @MainActor
    static func deleteBackward(count: Int) {
        guard count > 0 else { return }
        for _ in 0..<count {
            postKey(51, flags: []) // Keycode 51 is Backspace / Delete
        }
    }
}

enum Permissions {
    static var accessibility: Bool { AXIsProcessTrusted() }
    static var inputMonitoring: Bool { CGPreflightListenEventAccess() }

    static func requestAccessibility() {
        let opts = [kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String: true] as CFDictionary
        _ = AXIsProcessTrustedWithOptions(opts)
    }

    static func requestInputMonitoring() { _ = CGRequestListenEventAccess() }

    static func openSettings(_ anchor: String) {
        if let url = URL(string: "x-apple.systempreferences:com.apple.preference.security?\(anchor)") {
            NSWorkspace.shared.open(url)
        }
    }
}
